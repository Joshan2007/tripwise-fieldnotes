import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
let preferenceChange,plays=0,cancels=0;
const preference={matches:true,addEventListener:(_,fn)=>preferenceChange=fn};
const main={querySelector:()=>null,querySelectorAll:()=>[]};
const dialog={open:false};
const count={textContent:'0'};
const element={animate:()=>{plays++;return {finished:new Promise(()=>{}),cancel:()=>cancels++};}};
const context=vm.createContext({window:{matchMedia:()=>preference,addEventListener(){}},document:{querySelector:s=>s==='#main'?main:s==='#details'?dialog:count,addEventListener(){}},MutationObserver:class{observe(){}},Element:class{},queueMicrotask,console});
vm.runInContext(await readFile(new URL('../dist/motion.js',import.meta.url),'utf8'),context);
context.element=element;
vm.runInContext('play(element,[{opacity:0},{opacity:1}])',context);
assert.equal(plays,0,'Reduced motion must suppress JavaScript animation');
preference.matches=false;
vm.runInContext('play(element,[{opacity:0},{opacity:1}])',context);
assert.equal(plays,1,'Animations run when motion is allowed');
preference.matches=true;preferenceChange();
assert.equal(cancels,1,'Changing the preference cancels active motion');
assert.doesNotThrow(()=>vm.runInContext('play(null,[])',context));
console.log('PASS: reduced-motion suppression, allowed animation, live preference cancellation, and graceful IntersectionObserver fallback.');
